// Writes packages/raiminiscence-mcp/README.md, the page npm shows for the package, from the root
// README.md so the two never drift. Everything from "## Contributing" on is repo-only and is
// replaced by packages/raiminiscence-mcp/docs/readme-package-sections.md. Relative links are made
// absolute: npm does not resolve them against a package in a monorepo subfolder.
// Run `pnpm readme:generate` to write, or `pnpm readme:check` (CI and the pre-commit hook) to fail
// without writing if the package README is stale.
import { readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";

const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url));
const ROOT_README = "README.md";
const PACKAGE_SECTIONS = "packages/raiminiscence-mcp/docs/readme-package-sections.md";
const PACKAGE_README = "packages/raiminiscence-mcp/README.md";

const BLOB = "https://github.com/windagency/raiminiscence/blob/main/";
const TREE = "https://github.com/windagency/raiminiscence/tree/main/";
const RAW = "https://raw.githubusercontent.com/windagency/raiminiscence/main/";

const NOTICE = `<!-- Generated by scripts/generate-package-readme.ts from ${ROOT_README} and ${PACKAGE_SECTIONS}. Do not edit: run \`pnpm readme:generate\`. -->`;
const REPO_ONLY_FROM = "\n## Contributing\n";
const NAV_DOCUMENTATION = " · [Documentation](#documentation)";

// A target with a scheme or a leading "#" is already absolute or in-page. The link text may hold
// one nested image, as a badge does.
const RELATIVE_LINK = /(!?)\[((?:[^[\]]|\[[^\]]*\]\([^)]*\))*)\]\((?![a-z][a-z0-9+.-]*:|#)(?:\.\/)?([^)\s]+)\)/gi;

// `isFolder` gets a repo-relative path without its "#anchor", and picks GitHub's tree view over blob.
export function buildPackageReadme(rootReadme: string, packageSections: string, isFolder: (path: string) => boolean): string {
  const cut = rootReadme.indexOf(REPO_ONLY_FROM);
  if (cut === -1) throw new Error(`${ROOT_README} has no "## Contributing" heading to cut the package README at.`);
  const shared = rootReadme.slice(0, cut);
  if (!shared.includes(NAV_DOCUMENTATION)) {
    throw new Error(`${ROOT_README}'s navigation line has no "[Documentation](#documentation)" link to add Configuration before.`);
  }
  const body = shared
    .replace(NAV_DOCUMENTATION, ` · [Configuration](#configuration)${NAV_DOCUMENTATION}`)
    .replace(RELATIVE_LINK, (_match, bang: string, text: string, target: string) => {
      if (bang) return `![${text}](${RAW}${target})`;
      return `[${text}](${isFolder(target.split("#")[0] ?? target) ? TREE : BLOB}${target})`;
    });
  return `${NOTICE}\n\n${body.trimEnd()}\n\n${packageSections.trim()}\n`;
}

// A link to a path that does not exist fails here, rather than shipping a dead link to npm.
const isFolder = (path: string) => statSync(join(REPO_ROOT, path)).isDirectory();

async function main(): Promise<void> {
  const read = (file: string) => readFileSync(join(REPO_ROOT, file), "utf8");
  const target = join(REPO_ROOT, PACKAGE_README);
  // Rewritten links widen tables, so Prettier re-aligns them as `pnpm format` would.
  const config = await resolveConfig(target);
  const generated = await format(buildPackageReadme(read(ROOT_README), read(PACKAGE_SECTIONS), isFolder), { ...config, filepath: target });

  if (!process.argv.includes("--check")) {
    writeFileSync(target, generated);
    return;
  }
  if (read(PACKAGE_README) !== generated) {
    console.error(`${PACKAGE_README} is stale. Run \`pnpm readme:generate\` and commit the result.`);
    process.exitCode = 1;
    return;
  }
  console.log(`${PACKAGE_README} is up to date.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
