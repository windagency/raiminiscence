import { describe, expect, it } from "vitest";
import { buildPackageReadme } from "../../scripts/generate-package-readme.js";

const ROOT_README = `# rAIminiscence

[![License: MIT](https://img.shields.io/badge/License-MIT-yellow.svg)](./LICENSE)

[Quick start](#quick-start) · [How it works](#how-it-works) · [Documentation](#documentation)

![Decay curves](./docs/images/decay-curves.svg)

See the [user guide](./docs/user-guide.md#install), the [ADRs](./docs/adr/), [hooks](./packages/raiminiscence-hooks)
and [hippo-memory](https://github.com/kitfunso/hippo-memory).

## Documentation

Docs.

## Contributing

Run the tests.

## License

[MIT](./LICENSE).
`;

// The fixture's folders; every other target is a file.
const isFolder = (path: string) => ["docs/adr/", "packages/raiminiscence-hooks"].includes(path);

const SECTIONS = `## Configuration

Nothing is required.
`;

describe("buildPackageReadme", () => {
  it("opens with a notice that the file is generated, then the root README's title", () => {
    const [notice, , title] = buildPackageReadme(ROOT_README, SECTIONS, isFolder).split("\n");

    expect(notice).toMatch(/^<!-- Generated by scripts\/generate-package-readme\.ts .* Do not edit/);
    expect(title).toBe("# rAIminiscence");
  });

  it("points relative links at GitHub, since npm cannot resolve them", () => {
    const readme = buildPackageReadme(ROOT_README, SECTIONS, isFolder);

    expect(readme).toContain("![Decay curves](https://raw.githubusercontent.com/windagency/raiminiscence/main/docs/images/decay-curves.svg)");
    expect(readme).toContain("[user guide](https://github.com/windagency/raiminiscence/blob/main/docs/user-guide.md#install)");
    expect(readme).toContain("[ADRs](https://github.com/windagency/raiminiscence/tree/main/docs/adr/)");
    expect(readme).toContain("[hooks](https://github.com/windagency/raiminiscence/tree/main/packages/raiminiscence-hooks)");
  });

  it("points a badge's link at GitHub too, though the badge image sits inside the link text", () => {
    expect(buildPackageReadme(ROOT_README, SECTIONS, isFolder)).toContain(
      "[![License: MIT](https://img.shields.io/badge/License-MIT-yellow.svg)](https://github.com/windagency/raiminiscence/blob/main/LICENSE)",
    );
  });

  it("leaves absolute links and in-page anchors alone", () => {
    const readme = buildPackageReadme(ROOT_README, SECTIONS, isFolder);

    expect(readme).toContain("[hippo-memory](https://github.com/kitfunso/hippo-memory)");
    expect(readme).toContain("[Quick start](#quick-start)");
  });

  it("replaces everything from Contributing on with the package's own sections", () => {
    const readme = buildPackageReadme(ROOT_README, SECTIONS, isFolder);

    expect(readme).not.toContain("## Contributing");
    expect(readme).not.toContain("Run the tests.");
    expect(readme.trimEnd().endsWith("## Configuration\n\nNothing is required.")).toBe(true);
  });

  it("adds the package's Configuration section to the navigation line", () => {
    expect(buildPackageReadme(ROOT_README, SECTIONS, isFolder)).toContain(
      "[How it works](#how-it-works) · [Configuration](#configuration) · [Documentation](#documentation)",
    );
  });

  it("fails rather than guessing when the root README lost a heading it cuts or extends at", () => {
    expect(() => buildPackageReadme(ROOT_README.replace("## Contributing", "## Contribute"), SECTIONS, isFolder)).toThrow(/## Contributing/);
    expect(() => buildPackageReadme(ROOT_README.replace(" · [Documentation](#documentation)", ""), SECTIONS, isFolder)).toThrow(/navigation/);
  });
});
